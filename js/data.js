// בונה סולם שלבים: לכל מספר חזרות — כל אחת מאפשרויות הסטים
function ladder(v, setsList, repsList, cue, extra = {}) {
  const out = [];
  for (const r of repsList) for (const s of setsList) out.push({ v, s, r, cue, ...extra });
  return out;
}

